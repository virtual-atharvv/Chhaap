import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import { createReadStream, createWriteStream } from 'node:fs';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';
import { Transform } from 'node:stream';
import { db } from '@chhaap/db';
import { loadConfig } from './config.js';

export interface SavedUpload {
  storageKey: string;
  filePath: string;
  originalName: string;
  mime: string;
  sizeBytes: number;
  sha256: string;
}

const ALLOWED_EXTENSIONS = new Set([
  '.pdf',
  '.jpg',
  '.jpeg',
  '.png',
  '.doc',
  '.docx',
  '.ppt',
  '.pptx',
  '.xls',
  '.xlsx',
  '.odt',
  '.odp',
  '.ods'
]);

export class StorageService {
  private uploadsDir: string;
  private previewsDir: string;
  private sweeperInterval: NodeJS.Timeout | null = null;

  constructor(baseDir: string = process.env.CHHAAP_DATA_DIR || path.join(process.cwd(), 'data')) {
    this.uploadsDir = path.join(baseDir, 'uploads');
    this.previewsDir = path.join(baseDir, 'previews');
  }

  async init(): Promise<void> {
    await fs.mkdir(this.uploadsDir, { recursive: true, mode: 0o700 });
    await fs.mkdir(this.previewsDir, { recursive: true, mode: 0o700 });
    // Ensure permissions are tightened even if the directory already existed.
    await fs.chmod(this.uploadsDir, 0o700).catch(() => {});
    await fs.chmod(this.previewsDir, 0o700).catch(() => {});
  }

  getUploadsPath(): string {
    return this.uploadsDir;
  }

  getPreviewsPath(): string {
    return this.previewsDir;
  }

  getFilePath(storageKey: string): string {
    return path.join(this.uploadsDir, path.basename(storageKey));
  }

  getPreviewPath(filename: string): string {
    return path.join(this.previewsDir, path.basename(filename));
  }

  /**
   * Sanitises a user-supplied filename. Storage keys are always generated by
   * the server; the original name is display-only.
   */
  sanitizeFilename(originalName: string): string {
    const base = path.basename(originalName || 'document');
    const cleaned = base.replace(/[^a-zA-Z0-9._-]/g, '_').replace(/^\.+/, '_');
    return (cleaned || 'document').slice(0, 180);
  }

  /**
   * Validates magic bytes. Extension/mime alone are never trusted.
   */
  validateMagicBytes(
    head: Buffer,
    filename: string
  ): { valid: boolean; detectedMime: string; error?: string } {
    if (head.length < 4) {
      return { valid: false, detectedMime: '', error: 'File is empty or too small' };
    }

    if (head.subarray(0, 4).toString('ascii') === '%PDF') {
      const text = head.toString('latin1');
      if (text.includes('/Encrypt')) {
        return {
          valid: false,
          detectedMime: 'application/pdf',
          error: 'Password-protected PDFs are not supported yet. Please remove the password and re-upload.'
        };
      }
      return { valid: true, detectedMime: 'application/pdf' };
    }

    if (head[0] === 0xff && head[1] === 0xd8 && head[2] === 0xff) {
      return { valid: true, detectedMime: 'image/jpeg' };
    }

    if (head[0] === 0x89 && head[1] === 0x50 && head[2] === 0x4e && head[3] === 0x47) {
      return { valid: true, detectedMime: 'image/png' };
    }

    // ZIP container: DOCX/PPTX/XLSX/ODF are ZIP files.
    if (head[0] === 0x50 && head[1] === 0x4b && head[2] === 0x03 && head[3] === 0x04) {
      const ext = path.extname(filename).toLowerCase();
      if (ALLOWED_EXTENSIONS.has(ext)) {
        return { valid: true, detectedMime: 'application/zip' };
      }
      return {
        valid: false,
        detectedMime: 'application/zip',
        error: 'ZIP archives are not accepted. Please upload a PDF or an Office document.'
      };
    }

    return {
      valid: false,
      detectedMime: '',
      error: 'Unsupported file type. Upload PDF, DOCX, PPTX, XLSX, JPEG or PNG.'
    };
  }

  private async writeValidated(
    source: NodeJS.ReadableStream,
    originalName: string
  ): Promise<SavedUpload> {
    const config = loadConfig();
    await this.init();

    const safeName = this.sanitizeFilename(originalName);
    const ext = path.extname(safeName).toLowerCase();
    if (!ALLOWED_EXTENSIONS.has(ext)) {
      throw new Error('Unsupported file extension. Upload PDF, DOCX, PPTX, XLSX, JPEG or PNG.');
    }

    const storageKey = `${Date.now()}-${crypto.randomUUID()}${ext}`;
    const filePath = path.join(this.uploadsDir, storageKey);

    const hash = crypto.createHash('sha256');
    let size = 0;
    const headChunks: Buffer[] = [];
    let headLength = 0;

    const inspector = new Transform({
      transform(chunk: Buffer, _encoding, callback) {
        size += chunk.length;
        if (size > config.maxUploadBytes) {
          callback(
            new Error(
              `File exceeds the maximum allowed size of ${Math.round(
                config.maxUploadBytes / (1024 * 1024)
              )} MB`
            )
          );
          return;
        }
        hash.update(chunk);
        if (headLength < 4096) {
          const piece = chunk.subarray(0, Math.min(chunk.length, 4096 - headLength));
          headChunks.push(piece);
          headLength += piece.length;
        }
        callback(null, chunk);
      }
    });

    try {
      await pipeline(source, inspector, createWriteStream(filePath, { mode: 0o600 }));
    } catch (err) {
      await fs.unlink(filePath).catch(() => {});
      throw err;
    }

    const head = Buffer.concat(headChunks);
    const magic = this.validateMagicBytes(head, safeName);
    if (!magic.valid) {
      await fs.unlink(filePath).catch(() => {});
      throw new Error(magic.error || 'Invalid file format');
    }

    return {
      storageKey,
      filePath,
      originalName: safeName,
      mime: magic.detectedMime,
      sizeBytes: size,
      sha256: hash.digest('hex')
    };
  }

  async saveStream(source: NodeJS.ReadableStream, originalName: string): Promise<SavedUpload> {
    return this.writeValidated(source, originalName);
  }

  async saveBuffer(buffer: Buffer, originalName: string): Promise<SavedUpload> {
    const { Readable } = await import('node:stream');
    return this.writeValidated(Readable.from(buffer), originalName);
  }

  /**
   * Replaces the uploaded original with the print-ready PDF produced by the
   * analysis pipeline. Returns the file's final storage metadata.
   */
  async commitPrintedPdf(
    upload: SavedUpload,
    printedPdfPath: string,
    printedSha256: string,
    printedSizeBytes: number
  ): Promise<SavedUpload> {
    if (path.resolve(printedPdfPath) === path.resolve(upload.filePath)) {
      return upload;
    }

    const finalKey = `${Date.now()}-${crypto.randomUUID()}.pdf`;
    const finalPath = path.join(this.uploadsDir, finalKey);
    await fs.copyFile(printedPdfPath, finalPath);
    await fs.chmod(finalPath, 0o600).catch(() => {});
    await fs.unlink(printedPdfPath).catch(() => {});
    await fs.unlink(upload.filePath).catch(() => {});

    return {
      storageKey: finalKey,
      filePath: finalPath,
      originalName: upload.originalName,
      mime: 'application/pdf',
      sizeBytes: printedSizeBytes,
      sha256: printedSha256
    };
  }

  createReadStream(storageKey: string): NodeJS.ReadableStream {
    return createReadStream(this.getFilePath(storageKey));
  }

  /**
   * Starts the persistent deletion sweeper. Files are deleted from disk even
   * after an API restart because `delete_after` is persisted in the database.
   */
  startSweeper(intervalMs = 60_000): void {
    if (this.sweeperInterval) clearInterval(this.sweeperInterval);
    this.sweeperInterval = setInterval(() => {
      void this.sweepExpiredFiles();
    }, intervalMs);
    this.sweeperInterval.unref?.();
  }

  stopSweeper(): void {
    if (this.sweeperInterval) {
      clearInterval(this.sweeperInterval);
      this.sweeperInterval = null;
    }
  }

  async sweepExpiredFiles(): Promise<number> {
    try {
      const expiredFiles = await db.getFilesPendingDeletion(new Date());
      let deletedCount = 0;
      for (const file of expiredFiles) {
        if (await this.deleteFile(file.id)) deletedCount++;
      }
      if (deletedCount > 0) {
        console.log(`[storage] deleted ${deletedCount} expired file(s)`);
      }
      return deletedCount;
    } catch (err) {
      console.error('[storage] sweeper failed:', err);
      return 0;
    }
  }

  /** Persist a new deletion deadline (survives restarts). */
  async scheduleFileDeletion(fileId: string, delayMinutes = 15): Promise<void> {
    const file = await db.getFileById(fileId);
    if (!file) return;
    const deleteAfter = new Date(Date.now() + delayMinutes * 60 * 1000).toISOString();
    await db.updateFile(fileId, { deleteAfter });
  }

  async deleteFile(fileId: string): Promise<boolean> {
    const file = await db.getFileById(fileId);
    if (!file || file.deletedAt) return false;

    try {
      await fs.unlink(this.getFilePath(file.storageKey)).catch(() => {});
      if (file.convertedPdfKey && file.convertedPdfKey !== file.storageKey) {
        await fs.unlink(this.getFilePath(file.convertedPdfKey)).catch(() => {});
      }
      for (const preview of file.previewKeys ?? []) {
        await fs.unlink(this.getPreviewPath(preview)).catch(() => {});
      }
      await db.markFileDeleted(fileId);
      return true;
    } catch (err) {
      console.error(`[storage] failed to delete file ${fileId}:`, err);
      return false;
    }
  }

  private fileUrlSecret(): string {
    return process.env.FILE_URL_SECRET || loadConfig().jwtSecret;
  }

  /** Short-lived signed URL for the shop agent to download a print job. */
  signedFileUrl(baseUrl: string, fileId: string, ttlSeconds?: number): string {
    const ttl = ttlSeconds ?? loadConfig().fileUrlTtlSeconds;
    const exp = Math.floor(Date.now() / 1000) + ttl;
    const signature = crypto
      .createHmac('sha256', this.fileUrlSecret())
      .update(`${fileId}.${exp}`)
      .digest('hex');
    return `${baseUrl.replace(/\/$/, '')}/v1/files/${encodeURIComponent(
      fileId
    )}/download?exp=${exp}&sig=${signature}`;
  }

  verifyFileSignature(fileId: string, expRaw: string | undefined, signature: string | undefined): boolean {
    const exp = parseInt(expRaw ?? '', 10);
    if (!Number.isFinite(exp) || !signature) return false;
    if (exp < Math.floor(Date.now() / 1000)) return false;
    const expected = crypto
      .createHmac('sha256', this.fileUrlSecret())
      .update(`${fileId}.${exp}`)
      .digest('hex');
    const a = Buffer.from(expected);
    const b = Buffer.from(signature);
    if (a.length !== b.length) return false;
    return crypto.timingSafeEqual(a, b);
  }
}

export const storage = new StorageService();
